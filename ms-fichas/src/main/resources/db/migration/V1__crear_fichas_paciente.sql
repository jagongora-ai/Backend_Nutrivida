CREATE TABLE fichas_paciente (
    id BIGINT NOT NULL AUTO_INCREMENT,
    nombre VARCHAR(120) NOT NULL,
    rut VARCHAR(20) NOT NULL,
    edad INT NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    correo VARCHAR(160) NOT NULL,
    enfermedades VARCHAR(1000),
    alergias VARCHAR(1000),
    medicamentos VARCHAR(1000),
    alimentacion VARCHAR(1000),
    comidas VARCHAR(500),
    agua VARCHAR(500),
    actividad VARCHAR(1000),
    peso DECIMAL(6,2) NOT NULL,
    estatura DECIMAL(4,2) NOT NULL,
    imc DECIMAL(5,2) NOT NULL,
    objetivo VARCHAR(1000),
    observaciones VARCHAR(2000),
    recomendaciones VARCHAR(2000),
    id_medico VARCHAR(100) NOT NULL,
    PRIMARY KEY (id),
    INDEX idx_ficha_medico_nombre (id_medico, nombre)
);
